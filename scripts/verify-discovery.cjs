const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('src/lib/discovery.ts', 'utf8');
const compiled = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS}}).outputText;
const context = {exports: {}};
vm.runInNewContext(compiled, context);
const {matchesSearch, mapsUrl, validateSuggestion, suggestionItem} = context.exports;
const item = {title: 'Praça da Liberdade', category: 'Cultura', location: 'Belo Horizonte', description: 'Jardins e arquitetura'};
assert.equal(matchesSearch(item, ' LIBERDADE  praça '), true, 'Search ignores accents, whitespace, and case');
assert.equal(matchesSearch(item, 'cultura horizonte'), true, 'All query words can match different fields');
assert.equal(matchesSearch(item, 'praça inexistente'), false, 'A missing word rejects a result');
assert.equal(matchesSearch(item, ''), true);
const location = 'BH & rua / #1';
assert.equal(new URL(mapsUrl(location)).searchParams.get('query'), location, 'Map links safely encode user input');
const draft = {title: 'Café do bairro', category: 'Gastronomia', location: 'Savassi', description: 'Um café com um jardim bonito.'};
assert.equal(validateSuggestion(draft), null);
assert.ok(validateSuggestion({...draft, title: '  '}));
assert.ok(validateSuggestion({...draft, title: 'a'.repeat(81)}));
assert.ok(validateSuggestion({...draft, category: 'Administrador'}));
assert.ok(validateSuggestion({...draft, description: 'curta'}));
const shared = suggestionItem({...draft, id: '123'});
assert.equal(shared.id, 'community:123', 'Shared suggestions never collide with demo identifiers');
assert.equal(shared.image, '/images/uai-bora-oficial.png');
console.log('12 verificações de busca, links e validação passaram.');
